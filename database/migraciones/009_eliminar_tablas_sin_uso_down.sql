CREATE TABLE IF NOT EXISTS public.autorizacion_acceso (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id integer REFERENCES public.usuario(id),
    conductor_id integer REFERENCES public.conductor(id),
    parqueadero_id integer REFERENCES public.parqueadero(id),
    dia_semana smallint,
    hora_inicio time without time zone,
    hora_fin time without time zone,
    fecha_inicio date,
    fecha_fin date,
    motivo character varying(255),
    estado boolean DEFAULT true NOT NULL,
    fecha_creacion timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_autorizacion_dia CHECK (dia_semana IS NULL OR (dia_semana >= 1 AND dia_semana <= 7)),
    CONSTRAINT ck_autorizacion_fechas CHECK (fecha_inicio IS NULL OR fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT ck_autorizacion_horas CHECK (hora_inicio IS NULL OR hora_fin IS NULL OR hora_fin > hora_inicio),
    CONSTRAINT ck_autorizacion_responsable CHECK (usuario_id IS NOT NULL OR conductor_id IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS public.captura_placa (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placa_detectada character varying(10) NOT NULL,
    imagen_url character varying(500),
    confianza numeric(5,2),
    parqueadero_id integer NOT NULL REFERENCES public.parqueadero(id) DEFERRABLE,
    vehiculo_id integer REFERENCES public.vehiculo(id) DEFERRABLE,
    registro_acceso_id integer REFERENCES public.registro_acceso(id) DEFERRABLE,
    verificada boolean DEFAULT false NOT NULL,
    usuario_verifica_id integer REFERENCES public.usuario(id) DEFERRABLE,
    fecha_hora timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    placa_normalizada character varying(10),
    motor_ocr character varying(50),
    procesada boolean DEFAULT false NOT NULL,
    fecha_procesamiento timestamp without time zone,
    error_ocr character varying(500),
    direccion_captura character varying(10),
    origen character varying(30) DEFAULT 'NAVEGADOR' NOT NULL,
    CONSTRAINT ck_captura_placa_confianza CHECK (confianza IS NULL OR (confianza >= 0 AND confianza <= 100)),
    CONSTRAINT ck_captura_placa_direccion CHECK (direccion_captura IS NULL OR direccion_captura IN ('ENTRADA', 'SALIDA'))
);

CREATE TABLE IF NOT EXISTS public.intento_ocr (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    captura_placa_id integer NOT NULL REFERENCES public.captura_placa(id) ON DELETE CASCADE,
    motor character varying(50) NOT NULL,
    placa_detectada character varying(10),
    placa_normalizada character varying(10),
    confianza numeric(5,2),
    tiempo_procesamiento_ms integer,
    exitoso boolean DEFAULT false NOT NULL,
    error character varying(500),
    fecha_hora timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_intento_ocr_confianza CHECK (confianza IS NULL OR (confianza >= 0 AND confianza <= 100)),
    CONSTRAINT ck_intento_ocr_tiempo CHECK (tiempo_procesamiento_ms IS NULL OR tiempo_procesamiento_ms >= 0)
);

CREATE TABLE IF NOT EXISTS public.encuesta (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo character varying(150) NOT NULL,
    descripcion character varying(500),
    fecha_inicio date NOT NULL,
    fecha_fin date,
    estado boolean DEFAULT true NOT NULL,
    CONSTRAINT ck_encuesta_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE IF NOT EXISTS public.valoracion (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encuesta_id integer NOT NULL REFERENCES public.encuesta(id) DEFERRABLE,
    usuario_id integer NOT NULL REFERENCES public.usuario(id) DEFERRABLE,
    registro_acceso_id integer REFERENCES public.registro_acceso(id) DEFERRABLE,
    calificacion smallint NOT NULL,
    comentario character varying(500),
    fecha_hora timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_valoracion_calificacion CHECK (calificacion >= 1 AND calificacion <= 5)
);

CREATE TABLE IF NOT EXISTS public.licencia_conduccion (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conductor_id integer NOT NULL REFERENCES public.conductor(id) DEFERRABLE,
    numero_licencia character varying(20) NOT NULL,
    categoria character varying(10) NOT NULL,
    fecha_expedicion date,
    fecha_vencimiento date,
    estado boolean DEFAULT true NOT NULL
);

CREATE TABLE IF NOT EXISTS public.parqueadero_ip_autorizada (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parqueadero_id integer NOT NULL REFERENCES public.parqueadero(id) ON DELETE CASCADE,
    direccion_ip inet NOT NULL,
    descripcion character varying(255),
    estado boolean DEFAULT true NOT NULL,
    fecha_creacion timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_ip_parqueadero UNIQUE (parqueadero_id, direccion_ip)
);

