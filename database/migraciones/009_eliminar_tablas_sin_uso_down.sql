CREATE OR REPLACE FUNCTION public.fn_normalizar_placa() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    IF NEW.placa_detectada IS NOT NULL THEN
        NEW.placa_normalizada := UPPER(REGEXP_REPLACE(TRIM(NEW.placa_detectada), '[^A-Za-z0-9]', '', 'g'));
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_captura_placa_normalizar ON public.captura_placa;
CREATE TRIGGER trg_captura_placa_normalizar
    BEFORE INSERT OR UPDATE OF placa_detectada, placa_normalizada ON public.captura_placa
    FOR EACH ROW EXECUTE FUNCTION public.fn_normalizar_placa();

CREATE OR REPLACE FUNCTION public.fn_usuario_autorizado_acceso(p_usuario_id integer, p_conductor_id integer, p_parqueadero_id integer, p_momento timestamp without time zone DEFAULT CURRENT_TIMESTAMP) RETURNS boolean
    LANGUAGE plpgsql
    AS $$
DECLARE
    v_dia smallint := EXTRACT(ISODOW FROM p_momento)::smallint;
    v_hora time := p_momento::time;
BEGIN
    RETURN EXISTS (
        SELECT 1
        FROM public.autorizacion_acceso a
        WHERE a.estado = true
          AND (a.usuario_id = p_usuario_id OR a.conductor_id = p_conductor_id)
          AND (a.parqueadero_id IS NULL OR a.parqueadero_id = p_parqueadero_id)
          AND (a.dia_semana IS NULL OR a.dia_semana = v_dia)
          AND (a.hora_inicio IS NULL OR a.hora_fin IS NULL OR v_hora BETWEEN a.hora_inicio AND a.hora_fin)
          AND (a.fecha_inicio IS NULL OR p_momento::date >= a.fecha_inicio)
          AND (a.fecha_fin IS NULL OR p_momento::date <= a.fecha_fin)
    );
END;
$$;

CREATE OR REPLACE VIEW public.v_autorizaciones_activas AS
 SELECT a.id AS autorizacion_id, a.usuario_id, u.nombre AS usuario, a.conductor_id,
    c.nombre_apellidos AS conductor, a.parqueadero_id, p.nombre AS parqueadero,
    a.dia_semana, a.hora_inicio, a.hora_fin, a.fecha_inicio, a.fecha_fin, a.motivo, a.estado
   FROM public.autorizacion_acceso a
     LEFT JOIN public.usuario u ON u.id = a.usuario_id
     LEFT JOIN public.conductor c ON c.id = a.conductor_id
     LEFT JOIN public.parqueadero p ON p.id = a.parqueadero_id
  WHERE a.estado = true
    AND (a.fecha_inicio IS NULL OR a.fecha_inicio <= CURRENT_DATE)
    AND (a.fecha_fin IS NULL OR a.fecha_fin >= CURRENT_DATE);

CREATE OR REPLACE VIEW public.v_reconocimiento_placas AS
 SELECT cp.id AS captura_id, cp.placa_detectada, cp.placa_normalizada, cp.confianza, cp.motor_ocr,
    cp.procesada, cp.verificada, cp.direccion_captura, cp.fecha_hora, cp.fecha_procesamiento,
    cp.error_ocr, cp.vehiculo_id, v.placa AS placa_registrada, v.tipo AS tipo_vehiculo,
    cp.parqueadero_id, p.nombre AS parqueadero, cp.registro_acceso_id
   FROM public.captura_placa cp
     LEFT JOIN public.vehiculo v ON v.id = cp.vehiculo_id
     JOIN public.parqueadero p ON p.id = cp.parqueadero_id;

CREATE OR REPLACE VIEW public.v_desempeno_satisfaccion AS
 SELECT e.id AS encuesta_id, e.titulo,
    count(v.id) AS total_valoraciones,
    round(avg(v.calificacion), 2) AS promedio_calificacion,
    count(v.id) FILTER (WHERE v.calificacion >= 4) AS valoraciones_positivas,
    count(v.id) FILTER (WHERE v.calificacion <= 2) AS valoraciones_negativas
   FROM public.encuesta e
     LEFT JOIN public.valoracion v ON v.encuesta_id = e.id
  GROUP BY e.id, e.titulo;

